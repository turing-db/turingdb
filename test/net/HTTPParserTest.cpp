// Helper: feed raw bytes into a NetBuffer and run HTTPParser::analyze().
// Returns the result; swallows every exception except FatalException.
static net::HTTP::Result<bool> feedAndAnalyze(const char* data, size_t size) {
    if (size > net::NetBuffer::BUFFER_SIZE) {
        size = net::NetBuffer::BUFFER_SIZE;
    }

    net::NetBuffer buffer;
    auto writer = buffer.getWriter();
    writer.writeString(data, size);

    net::HTTPParser<net::URIParser> parser(&buffer);

    try {
        const auto result = parser.analyze();
        if (!result) {
            return BadResult(static_cast<net::HTTP::Error>(result.error()));
        }

        return result.value();
    } catch (const FatalException&) {
        throw;
    } catch (...) {
        throw;
    }

    return true;
}

// Convenience overload for std::string.
static net::HTTP::Result<bool> feedAndAnalyze(const std::string& s) {
    return feedAndAnalyze(s.data(), s.size());
}

