// -------------------------------------------------------------------
// URIParser: exactly MAX_PARAM_COUNT (8) params should succeed,
// 9 should be caught by the bounds check (not overflow).
// -------------------------------------------------------------------
TEST_F(HTTPParserCrashTest, TooManyQueryParams) {
    // 9 key=value pairs – the 9th triggers the off-by-one in
    // `if (i > MAX_PARAM_COUNT)` which should be `>=`.
    std::string req =
        "GET ?a=1&b=2&c=3&d=4&e=5&f=6&g=7&h=8&i=9 HTTP/1.1\r\n"
        "Content-Length: 0\r\n\r\n";
    EXPECT_NO_FATAL_FAILURE(feedAndAnalyze(req));
}

TEST_F(HTTPParserCrashTest, ExactlyMaxParams) {
    // 8 key=value pairs – should be fine.
    std::string req =
        "GET ?a=1&b=2&c=3&d=4&e=5&f=6&g=7&h=8 HTTP/1.1\r\n"
        "Content-Length: 0\r\n\r\n";
    auto result = feedAndAnalyze(req);
    EXPECT_TRUE(result.has_value());
}

TEST_F(HTTPParserCrashTest, WayTooManyQueryParams) {
    // 20 params – deep into overflow territory.
    std::string uri = "GET ?";
    for (int i = 0; i < 20; i++) {
        if (i > 0) uri += "&";
        uri += "p" + std::to_string(i) + "=v" + std::to_string(i);
    }
    uri += " HTTP/1.1\r\nContent-Length: 0\r\n\r\n";
    EXPECT_NO_FATAL_FAILURE(feedAndAnalyze(uri));
}

